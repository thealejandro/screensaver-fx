/// Signo sobre la letra. Cada `#` es un píxel de medio bloque (una celda de ancho, media fila de alto).
#[derive(Clone, Copy, PartialEq, Debug)]
pub enum Mark {
    Acute,
    Grave,
    Circumflex,
    Diaeresis,
    Tilde,
}

impl Mark {
    pub fn pixels(self, big: bool) -> &'static [&'static str] {
        match (self, big) {
            (Mark::Acute, true) => &["   ##", "  ## ", " ##  "],
            (Mark::Grave, true) => &["##   ", " ##  ", "  ## "],
            (Mark::Circumflex, true) => &["  ##  ", " #### ", "##  ##"],
            (Mark::Diaeresis, true) => &["###   ###", "###   ###"],
            (Mark::Tilde, true) => &[" ####  ##", "##  #### "],
            (Mark::Acute, false) => &["  ##", " ## "],
            (Mark::Grave, false) => &["##  ", " ## "],
            (Mark::Circumflex, false) => &[" ## ", "#  #"],
            (Mark::Diaeresis, false) => &["## ##", "## ##"],
            (Mark::Tilde, false) => &[" ## #", "# ## "],
        }
    }
}

/// Letra base y signo de las vocales acentuadas y la Ñ (ya en mayúscula).
pub fn decompose(c: char) -> Option<(char, Mark)> {
    use Mark::*;
    Some(match c {
        'Á' => ('A', Acute),
        'À' => ('A', Grave),
        'Â' => ('A', Circumflex),
        'Ä' => ('A', Diaeresis),
        'Ã' => ('A', Tilde),
        'É' => ('E', Acute),
        'È' => ('E', Grave),
        'Ê' => ('E', Circumflex),
        'Ë' => ('E', Diaeresis),
        'Í' => ('I', Acute),
        'Ì' => ('I', Grave),
        'Î' => ('I', Circumflex),
        'Ï' => ('I', Diaeresis),
        'Ó' => ('O', Acute),
        'Ò' => ('O', Grave),
        'Ô' => ('O', Circumflex),
        'Ö' => ('O', Diaeresis),
        'Õ' => ('O', Tilde),
        'Ú' => ('U', Acute),
        'Ù' => ('U', Grave),
        'Û' => ('U', Circumflex),
        'Ü' => ('U', Diaeresis),
        'Ñ' => ('N', Tilde),
        _ => return None,
    })
}

pub fn big(c: char) -> Option<&'static [&'static str; BIG_H]> {
    BIG.iter().find(|g| g.0 == c).map(|g| &g.1)
}

pub fn small(c: char) -> Option<&'static [&'static str; SMALL_H]> {
    SMALL.iter().find(|g| g.0 == c).map(|g| &g.1)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn check(name: &str, c: char, rows: &[&str]) {
        let w = rows[0].chars().count();
        assert!(w > 0, "{name} {c:?}");
        for r in rows {
            assert_eq!(r.chars().count(), w, "{name} {c:?}: filas de distinto ancho");
            assert!(r.chars().all(|ch| " █▀▄".contains(ch)), "{name} {c:?}: {r:?}");
        }
        if c != ' ' {
            assert!(rows.iter().any(|r| r.trim() != ""), "{name} {c:?} vacía");
        }
    }

    #[test]
    fn glyphs_are_rectangular_and_unique() {
        for (c, g) in BIG {
            check("grande", *c, g);
        }
        for (c, g) in SMALL {
            check("pequeña", *c, g);
        }
        for t in [BIG.iter().map(|g| g.0).collect::<Vec<_>>(), SMALL.iter().map(|g| g.0).collect()] {
            let mut s = t.clone();
            s.sort_unstable();
            s.dedup();
            assert_eq!(s.len(), t.len(), "letra repetida");
        }
        // Las dos fuentes cubren lo mismo, así que título y subtítulo se ven iguales.
        let (a, b): (Vec<char>, Vec<char>) = (BIG.iter().map(|g| g.0).collect(), SMALL.iter().map(|g| g.0).collect());
        assert_eq!(a, b);
        for c in ('A'..='Z').chain('0'..='9') {
            assert!(big(c).is_some() && small(c).is_some(), "{c}");
        }
    }

    #[test]
    fn marks_are_rectangular() {
        for m in [Mark::Acute, Mark::Grave, Mark::Circumflex, Mark::Diaeresis, Mark::Tilde] {
            for big in [true, false] {
                let p = m.pixels(big);
                assert!(!p.is_empty() && p.len() <= 3);
                let w = p[0].len();
                assert!(p.iter().all(|r| r.len() == w && r.bytes().all(|b| b == b'#' || b == b' ')), "{m:?}");
            }
        }
        for c in "ÁÉÍÓÚÜÑÀÈÌÒÙÂÊÎÔÛÄËÏÖÃÕ".chars() {
            let (base, _) = decompose(c).unwrap();
            assert!(big(base).is_some(), "{c}");
        }
    }
}
