/// Tilde o diéresis que va encima de una letra grande.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Mark {
    Acute,
    Grave,
    Circumflex,
    Diaeresis,
    Tilde,
}

impl Mark {
    /// Dos filas: la de arriba solo usa la mitad inferior y la de abajo la superior, así la
    /// marca queda separada de la letra por media fila.
    pub fn rows(self) -> [&'static str; MARK_H] {
        match self {
            Mark::Acute => ["  ▄▄▄", "▀▀▀  "],
            Mark::Grave => ["▄▄▄  ", "  ▀▀▀"],
            Mark::Circumflex => ["  ▄▄▄  ", "▀▀▀ ▀▀▀"],
            Mark::Diaeresis => ["▄▄▄ ▄▄▄", "▀▀▀ ▀▀▀"],
            Mark::Tilde => [" ▄▄▄    ▄", "▀   ▀▀▀▀ "],
        }
    }
}

/// Mayúscula sin marca y la marca que llevaba: 'é' -> ('E', Acute), 'ñ' -> ('N', Tilde).
pub fn decompose(ch: char) -> (char, Option<Mark>) {
    let up = ch.to_uppercase().next().unwrap_or(ch);
    let (base, mark) = match up {
        'Á' | 'É' | 'Í' | 'Ó' | 'Ú' | 'Ý' => (up, Mark::Acute),
        'À' | 'È' | 'Ì' | 'Ò' | 'Ù' => (up, Mark::Grave),
        'Â' | 'Ê' | 'Î' | 'Ô' | 'Û' => (up, Mark::Circumflex),
        'Ä' | 'Ë' | 'Ï' | 'Ö' | 'Ü' => (up, Mark::Diaeresis),
        'Ã' | 'Õ' | 'Ñ' => (up, Mark::Tilde),
        'Ç' => return ('C', None),
        _ => return (up, None),
    };
    let plain = match base {
        'Á' | 'À' | 'Â' | 'Ä' | 'Ã' => 'A',
        'É' | 'È' | 'Ê' | 'Ë' => 'E',
        'Í' | 'Ì' | 'Î' | 'Ï' => 'I',
        'Ó' | 'Ò' | 'Ô' | 'Ö' | 'Õ' => 'O',
        'Ú' | 'Ù' | 'Û' | 'Ü' => 'U',
        'Ý' => 'Y',
        _ => 'N',
    };
    (plain, Some(mark))
}

/// Letra grande (ya en mayúscula y sin marca).
pub fn big(ch: char) -> Option<&'static [&'static str; BIG_H]> {
    BIG.iter().find(|g| g.0 == ch).map(|g| &g.1)
}

/// Letra pequeña. La Ñ tiene dibujo propio; el resto de marcas se quitan.
pub fn small(ch: char) -> Option<&'static [&'static str; SMALL_H]> {
    let up = ch.to_uppercase().next().unwrap_or(ch);
    let key = if up == 'Ñ' { up } else { decompose(up).0 };
    SMALL.iter().find(|g| g.0 == key).map(|g| &g.1)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn check(name: char, rows: &[&str]) {
        let w = rows[0].chars().count();
        assert!(w > 0, "{name:?}");
        for r in rows {
            assert_eq!(r.chars().count(), w, "{name:?}: fila {r:?} de ancho distinto");
            assert!(r.chars().all(|c| " █▀▄".contains(c)), "{name:?}: {r:?}");
        }
    }

    #[test]
    fn glyphs_are_rectangular_block_art() {
        for (ch, rows) in BIG {
            check(*ch, rows);
        }
        for (ch, rows) in SMALL {
            check(*ch, rows);
        }
        for m in [Mark::Acute, Mark::Grave, Mark::Circumflex, Mark::Diaeresis, Mark::Tilde] {
            check('~', &m.rows());
        }
    }

    #[test]
    fn no_duplicated_glyphs_and_full_alphanumerics() {
        for table in [BIG.iter().map(|g| g.0).collect::<Vec<_>>(), SMALL.iter().map(|g| g.0).collect()] {
            let mut sorted = table.clone();
            sorted.sort_unstable();
            sorted.dedup();
            assert_eq!(sorted.len(), table.len());
        }
        for ch in ('A'..='Z').chain('0'..='9') {
            assert!(big(ch).is_some() && small(ch).is_some(), "{ch}");
            assert!(small(ch.to_ascii_lowercase()).is_some());
        }
    }

    #[test]
    fn decompose_latin() {
        assert_eq!(decompose('ñ'), ('N', Some(Mark::Tilde)));
        assert_eq!(decompose('ú'), ('U', Some(Mark::Acute)));
        assert_eq!(decompose('Ü'), ('U', Some(Mark::Diaeresis)));
        assert_eq!(decompose('ç'), ('C', None));
        assert_eq!(decompose('x'), ('X', None));
        assert_eq!(decompose('7'), ('7', None));
        assert!(small('ñ') != small('n'));
        assert_eq!(small('á'), small('A'));
    }
}
